def explain_aegis_alert(
    severity: str,
    title: str,
    message: str,
) -> dict:
    """Return a deterministic human-readable explanation for a security alert."""
    normalized_severity = severity.strip().lower()

    if normalized_severity == "critical":
        action = (
            "Immediately isolate the affected extension and investigate "
            "the associated network activity."
        )
    elif normalized_severity == "high":
        action = (
            "Investigate the affected extension and review its network "
            "activity before continuing normal use."
        )
    elif normalized_severity == "medium":
        action = (
            "Review the alert details and monitor the extension for "
            "additional suspicious behavior."
        )
    else:
        action = (
            "Review the alert and continue monitoring the extension "
            "for unusual activity."
        )

    return {
        "assistant": "Aegis",
        "severity": normalized_severity,
        "title": title,
        "alert": message,
        "explanation": (
            f"This alert has a {normalized_severity} severity level. "
            f"The alert '{title}' indicates the following security concern: "
            f"{message}"
        ),
        "recommended_action": action,
    }