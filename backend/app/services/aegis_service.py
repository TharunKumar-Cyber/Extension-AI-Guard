def get_aegis_response(message: str) -> dict:
    """Return a deterministic Aegis response based on the user's message."""
    normalized_message = message.strip().lower()

    if not normalized_message:
        return {
            "assistant": "Aegis",
            "message": "Please enter a security-related question or message.",
        }

    if "what is extension ai guard" in normalized_message:
        response = (
            "Extension AI Guard is a security platform designed to analyze "
            "browser extension network traffic and identify suspicious behavior."
        )
    elif "network traffic" in normalized_message:
        response = (
            "Network traffic analysis examines the requests, destinations, "
            "methods, headers, and other communication patterns generated by "
            "a browser extension."
        )
    elif "malicious extension" in normalized_message:
        response = (
            "A malicious browser extension is an extension that performs "
            "harmful or unauthorized actions, such as stealing sensitive data, "
            "communicating with suspicious destinations, or abusing browser permissions."
        )
    elif "how does aegis detect" in normalized_message:
        response = (
            "Aegis currently provides deterministic security guidance. "
            "The project's detection engine will analyze extension traffic "
            "and security events, which Aegis can later explain to users."
        )
    else:
        response = (
            "I am Aegis, the Extension AI Guard security assistant. "
            "I can help explain browser extension security, network traffic "
            "analysis, suspicious behavior, and safe security testing."
        )

    return {
        "assistant": "Aegis",
        "message": response,
    }

